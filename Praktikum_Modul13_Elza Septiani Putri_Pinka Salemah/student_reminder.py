from datetime import datetime, date

nama = input("masukkan nama : ")
tugas = input("masukkan tugas : ")
deadline = input("masukkan tanggal deadline (dd-mm-yyyy): ")

tanggal_deadline = datetime.strptime(deadline, "%d-%m-%Y").date()

hari_ini = date.today()

sisa_hari = (tanggal_deadline - hari_ini).days

print("\n===== PENGINGAT TUGAS =====")
print("Halo", nama)
print("Jangan lupa mengerjakan", tugas)
print("Deadline:", deadline)
print("Sisa waktu:", sisa_hari, "hari lagi!")